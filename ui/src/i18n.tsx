// Internationalization (i18n) for the operator console.
// Supports automatic browser locale detection plus manual switching between
// English (en) and Simplified Chinese (zh-CN), persisted in localStorage.
import { createContext, useCallback, useContext, useEffect, useMemo, useState, type ReactNode } from 'react';
import type { BotRequest, ReceiptStatus, ServiceInfo, SessionStatus, TaskStatus } from './api';

export type Locale = 'en' | 'zh-CN';
export type LanguagePref = 'auto' | Locale;

const LANG_KEY = 'acm.lang';

export interface ClientGuide {
  id: string;
  name: string;
  provider: string;
  clientKind: string;
  file: string;
  steps: string[];
  blocks: { label: string; code: string }[];
  note?: string;
}

function detectLocale(): Locale {
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh-CN';
  }
  return 'en';
}

function readInitialPref(): LanguagePref {
  try {
    const stored = window.localStorage.getItem(LANG_KEY);
    if (stored === 'auto' || stored === 'en' || stored === 'zh-CN') {
      return stored;
    }
  } catch {
    // Storage unavailable in restricted browser contexts.
  }
  return 'auto';
}

